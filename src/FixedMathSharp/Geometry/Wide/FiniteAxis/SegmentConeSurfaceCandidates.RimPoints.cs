using System;
using static FixedMathSharp.Geometry.CylinderContactAlgebra;
using static FixedMathSharp.Geometry.ContactQuadratic;

namespace FixedMathSharp.Geometry;

/// <content>Endpoint and axial-edge rim pairs, including exact rotational domains.</content>
internal static partial class SegmentConeSurfaceCandidates
{
    private static void AccumulateRimPoints(in SegmentConeSurfaceGeometry geometry, ref ConeSurfaceSelection selection)
    {
        int Words = geometry.Words;
        if (geometry.Radius.IsZero)
            return;
        int first = !geometry.Edge.IsZero && geometry.Edge.Y.IsZero || HasSlantedHorizontalRimFoot(geometry) ? -2
            : geometry.Edge.X.IsZero && geometry.Edge.Z.IsZero && !geometry.Edge.Y.IsZero ? -1 : 0;
        int last = geometry.Edge.IsZero ? 0 : 1;
        Span<ulong> values = stackalloc ulong[10 * Words];
        Span<int> signs = stackalloc int[10];
        Span<ulong> root = stackalloc ulong[Words];
        for (int endpoint = first; endpoint <= last; endpoint++)
        {
            if (endpoint < 0 && endpoint != first)
                continue;
            if (!TryGetRimPoint(geometry, endpoint, out WideDirection3d radialAxis, out Signed832 radialCoefficient,
                    out Signed576 axialOffset, out _, out _))
                continue;
            Signed832 radialSquare = radialAxis.SquaredLength;
            if (radialSquare.IsZero)
            {
                if (HasRimCircleDomain(geometry, axialOffset, endpoint, values, signs, root))
                    selection.Add(new SegmentConeSurfaceCandidate(geometry.Input, ConeSurfaceFeature.Rim,
                        ConeSurfaceFamily.RotationCircle, -2, endpoint, endpoint < 0 ? ConeSurfacePointLocation.Interior
                            : endpoint == 0 ? ConeSurfacePointLocation.Start : ConeSurfacePointLocation.End));
                continue;
            }
            Import(radialSquare, root);
            for (int branch = -1; branch <= 1; branch += 2)
            {
                BuildRimPointNormal(geometry, radialAxis, radialCoefficient, axialOffset, radialSquare, branch, values, signs);
                if (!AdmitsEndpointNormal(geometry.Edge, endpoint, values, signs, root))
                    continue;
                bool zero = At(values, signs, 0, Words).Sign(root) == 0 && At(values, signs, 1, Words).Sign(root) == 0 && At(values, signs, 2, Words).Sign(root) == 0;
                if (zero && !HasRimTouchDomain(geometry, radialAxis, branch, endpoint))
                    continue;
                selection.Add(new SegmentConeSurfaceCandidate(geometry.Input, ConeSurfaceFeature.Rim,
                    zero ? ConeSurfaceFamily.NormalCone : ConeSurfaceFamily.None,
                    branch > 0 ? -2 : -3, endpoint, endpoint < 0 ? ConeSurfacePointLocation.Interior
                        : endpoint == 0 ? ConeSurfacePointLocation.Start : ConeSurfacePointLocation.End));
            }
        }
    }

    private static bool HasSlantedHorizontalRimFoot(in SegmentConeSurfaceGeometry geometry)
    {
        int Words = geometry.Words;
        if (geometry.Edge.Y.IsZero || IsMeridionalRim(geometry)
            || geometry.Edge.X.IsZero && geometry.Edge.Z.IsZero)
            return false;
        // At a horizontal stationary normal both unsquared chart factors
        // vanish. The radial affine foot must lie exactly in the base plane:
        // C_y|E_rad|²-(C_rad.E_rad)E_y=0. Products are <596 bits.
        Span<ulong> difference = stackalloc ulong[Words];
        CylinderContactAlgebra.DifferenceOfProducts(CircularRimContactAlgebra.RadialDot(geometry.Edge, geometry.Edge),
            Signed832.ExtendValue(geometry.BaseOffset.Y), CircularRimContactAlgebra.RadialDot(geometry.BaseOffset, geometry.Edge),
            Signed832.ExtendValue(geometry.Edge.Y), difference, out int sign);
        return sign == 0;
    }

    private static bool HasRimTouchDomain(in SegmentConeSurfaceGeometry geometry, WideDirection3d radialAxis, int branch, int endpoint)
    {
        int Words = geometry.Words;
        // The rim normal cone is generated by inward side and upward base
        // normals. A nonzero nonnegative combination satisfies the segment
        // tangent condition exactly when their scalar projections straddle
        // zero (interior), or one generator has the endpoint's required sign.
        Span<ulong> values = stackalloc ulong[2 * Words];
        Span<int> signs = stackalloc int[2];
        Span<ulong> root = stackalloc ulong[Words];
        ContactQuadratic side = At(values, signs, 0, Words);
        side.Set(WideArithmetic.MultiplySigned832(CircularRimContactAlgebra.RadialDot(radialAxis, geometry.Edge), Signed192.Raw(geometry.Input.Height)));
        side.MultiplySign(-branch);
        Signed832 vertical = Signed832.ExtendValue(WideArithmetic.MultiplySigned576(geometry.Edge.Y, Signed192.Raw(geometry.Input.Radius)));
        Import(vertical, side.Radical); side.Signs[1] = -vertical.Sign;
        Import(radialAxis.SquaredLength, root);
        int sideSign = side.Sign(root), baseSign = geometry.Edge.Y.Sign;
        return endpoint < 0 ? sideSign == 0 || sideSign != baseSign
            : endpoint == 0 ? sideSign <= 0 || baseSign <= 0 : sideSign >= 0 || baseSign >= 0;
    }

    private static bool TryGetRimPoint(in SegmentConeSurfaceGeometry geometry, int endpoint,
        out WideDirection3d radialAxis, out Signed832 radialCoefficient, out Signed576 axialOffset,
        out Signed832 numerator, out Signed832 denominator)
    {
        int Words = geometry.Words;
        denominator = Signed832.ExtendValue(Signed576.ExtendValue(Signed192.Signed(1)));
        numerator = endpoint == 1 ? denominator : default;
        WideDirection3d point = endpoint == 1 ? geometry.B : geometry.A;
        radialAxis = new WideDirection3d(point.X, default, point.Z);
        radialCoefficient = radialAxis.SquaredLength;
        axialOffset = WideArithmetic.AddSigned576(point.Y, geometry.Cap);
        if (endpoint >= 0)
            return geometry.Finite.ContainsTransformedPoint(geometry.Finite.Transform(endpoint == 0
                ? geometry.Input.Segment.Start : geometry.Input.Segment.End));
        if (endpoint == -2)
        {
            radialAxis = new WideDirection3d(WideArithmetic.Negate(geometry.Edge.Z), default, geometry.Edge.X);
            denominator = radialAxis.SquaredLength;
            numerator = WideArithmetic.SubtractSigned832(default, CircularRimContactAlgebra.RadialDot(geometry.A, geometry.Edge));
            radialCoefficient = WideDirection3d.Dot(geometry.A, radialAxis);
            if (numerator.Sign <= 0 || WideArithmetic.SubtractSigned832(denominator, numerator).Sign <= 0)
                return false;
            Signed576 pointY = geometry.A.Y;
            if (!geometry.Edge.Y.IsZero)
            {
                // HasSlantedHorizontalRimFoot established this exact height.
                pointY = WideArithmetic.Negate(geometry.Cap);
                axialOffset = default;
            }
            Span<ulong> values = stackalloc ulong[8 * Words]; Span<int> signs = stackalloc int[8];
            ContactQuadratic x = At(values, signs, 0, Words), y = At(values, signs, 1, Words), z = At(values, signs, 2, Words), factor = At(values, signs, 3, Words);
            factor.Set(radialCoefficient); Scale(factor, radialAxis.X, x); Scale(factor, radialAxis.Z, z);
            factor.Set(denominator); Scale(factor, pointY, y);
            return ContainsCenteredRatio(geometry, x, y, z, denominator);
        }
        numerator = WideArithmetic.SubtractSigned832(default, Signed832.ExtendValue(geometry.BaseOffset.Y));
        denominator = Signed832.ExtendValue(geometry.Edge.Y);
        if (denominator.Sign < 0)
        {
            denominator = WideArithmetic.SubtractSigned832(default, denominator);
            numerator = WideArithmetic.SubtractSigned832(default, numerator);
        }
        if (numerator.Sign <= 0 || WideArithmetic.SubtractSigned832(denominator, numerator).Sign <= 0)
            return false;
        axialOffset = default;
        return WideArithmetic.SubtractSigned832(radialCoefficient,
            WideArithmetic.MultiplySigned576(geometry.Radius, geometry.Radius)).Sign <= 0;
    }

    private static void BuildRimPointNormal(in SegmentConeSurfaceGeometry geometry, WideDirection3d radialAxis,
        Signed832 radialCoefficient, Signed576 axialOffset, Signed832 radialSquare, int branch, Span<ulong> values, Span<int> signs)
    {
        int Words = geometry.Words;
        ContactQuadratic component = At(values, signs, 3, Words);
        for (int axis = 0; axis < 3; axis++)
        {
            Signed576 coordinate = axis == 1 ? axialOffset : Component(radialAxis, axis);
            component.Set(Signed832.ExtendValue(coordinate));
            ContactQuadratic normal = At(values, signs, axis, Words);
            Scale(component, axis == 1 ? radialSquare : radialCoefficient, normal);
            if (axis == 1) continue;
            Signed832 radical = WideArithmetic.MultiplySigned576(geometry.Radius, coordinate);
            Import(radical, normal.Radical); normal.Signs[1] = -branch * radical.Sign;
        }
    }

    private static bool AdmitsEndpointNormal(WideDirection3d edge, int endpoint,
        Span<ulong> values, Span<int> signs, ReadOnlySpan<ulong> root)
    {
        int Words = values.Length / signs.Length;
        ContactQuadratic sum = At(values, signs, 3, Words), product = At(values, signs, 4, Words);
        sum.Clear();
        for (int axis = 0; axis < 3; axis++)
        {
            Scale(At(values, signs, axis, Words), Signed832.ExtendValue(Component(edge, axis)), product);
            sum.Add(product);
        }
        int sign = sum.Sign(root);
        return endpoint < 0 ? sign == 0 : endpoint == 0 ? sign <= 0 : sign >= 0;
    }

    private static bool HasRimCircleDomain(in SegmentConeSurfaceGeometry geometry, Signed576 axialOffset, int endpoint,
        Span<ulong> values, Span<int> signs, Span<ulong> root)
    {
        int Words = geometry.Words;
        if (endpoint < 0)
            return true;
        ContactQuadratic bound = At(values, signs, 0, Words);
        bound.Set(WideArithmetic.MultiplySigned576(axialOffset, geometry.Edge.Y));
        Import(geometry.Radius, bound.Radical); bound.Signs[1] = endpoint == 0 ? -1 : 1;
        Import(CircularRimContactAlgebra.RadialDot(geometry.Edge, geometry.Edge), root);
        int sign = bound.Sign(root);
        return endpoint == 0 ? sign <= 0 : sign >= 0;
    }

    internal static FixedContactAnchors GetRimPointContact(in SegmentConeSurfaceCandidate candidate)
    {
        int Words = candidate.Input.Words;
        if (candidate.RootOrdinal <= -3)
            return GetMeridionalRimContact(candidate);
        var geometry = new SegmentConeSurfaceGeometry(candidate.Input);
        bool admitted = TryGetRimPoint(geometry, candidate.RootOrdinal, out WideDirection3d radialAxis,
            out Signed832 radialCoefficient, out Signed576 axialOffset, out Signed832 numerator, out Signed832 denominator);
        System.Diagnostics.Debug.Assert(admitted);
        Span<ulong> values = stackalloc ulong[10 * Words];
        Span<int> signs = stackalloc int[10];
        Span<ulong> root = stackalloc ulong[Words];
        Signed832 radialSquare = radialAxis.SquaredLength;
        Import(radialSquare, root);
        int branch = candidate.Chart == -2 ? 1 : -1;
        BuildRimPointNormal(geometry, radialAxis, radialCoefficient, axialOffset, radialSquare, branch, values, signs);
        Vector3d radial = MaterializeRadialDirection(radialAxis, candidate.Input.Radius, branch);
        return MaterializeRimPoint(geometry, numerator, denominator, values, signs, root, radial);
    }

    private static FixedContactAnchors MaterializeRimPoint(in SegmentConeSurfaceGeometry geometry,
        Signed832 numerator, Signed832 denominator, Span<ulong> normals, Span<int> normalSigns,
        ReadOnlySpan<ulong> root, Vector3d radial)
    {
        int Words = geometry.Words;
        Vector3d normal = MaterializeQuadraticNormal(normals, normalSigns, root, geometry.Input.ConeRotation);
        Span<ulong> values = stackalloc ulong[6 * Words];
        Span<int> signs = stackalloc int[6];
        ContactQuadratic square = At(values, signs, 0, Words), sum = At(values, signs, 1, Words), divisor = At(values, signs, 2, Words);
        sum.Clear();
        for (int axis = 0; axis < 3; axis++)
        {
            Multiply(At(normals, normalSigns, axis, Words), At(normals, normalSigns, axis, Words), root, square);
            sum.Add(square);
        }
        divisor.Clear();
        WideArithmetic.MultiplyMagnitudes(root, root, divisor.Rational);
        divisor.Signs[0] = 1;
        Span<ulong> scale = stackalloc ulong[Words], squaredScale = stackalloc ulong[Words];
        Import(Signed576.ExtendValue(geometry.RawScale), scale);
        WideArithmetic.MultiplyMagnitudes(scale, scale, squaredScale);
        Scale(divisor, squaredScale, 1, square);
        bool represented = TryRoundSquareRootRatio(sum, square, root, out Fixed64 depth);
        square.Set(numerator); divisor.Set(denominator);
        Vector3d point = RoundSourceSegmentPoint(geometry, square, divisor, ReadOnlySpan<ulong>.Empty);
        return new FixedContactAnchors(new FixedPointAnchor(geometry.Input.Origin, geometry.Input.Rotation, point),
            TriangleCircularGeometry.GetSupport(geometry.Input.Center, geometry.Input.ConeRotation, Signed192.Raw(geometry.Input.Height), radial, 1),
            normal, represented ? depth : Fixed64.MaxValue, !represented);
    }

    private static Vector3d MaterializeRadialDirection(WideDirection3d direction, Fixed64 radius, int orientation)
    {
        Span<ulong> values = stackalloc ulong[7 * Words];
        Span<int> signs = stackalloc int[7];
        values.Clear(); signs.Clear();
        for (int axis = 0; axis < 3; axis++)
        {
            Signed576 coordinate = Component(direction, axis);
            Import(coordinate, Slot(values, axis, Words)); signs[axis] = orientation * coordinate.Sign;
        }
        return WideConvexPrismRelations.GetConvexContactCandidateScaledNormal(new ConvexContactCandidate(values, signs, 0), radius);
    }

    private static Vector3d MaterializeQuadraticNormal(Span<ulong> normals, Span<int> normalSigns,
        ReadOnlySpan<ulong> root, FixedQuaternion rotation)
    {
        int Words = normals.Length / normalSigns.Length;
        // Meridional coefficients <996 bits and root <1595; rotating adds
        // <65 bits. Complete metric coefficients remain below 2130 bits.
        Span<ulong> local = stackalloc ulong[7 * Words], world = stackalloc ulong[7 * Words];
        Span<int> localSigns = stackalloc int[7], worldSigns = stackalloc int[7];
        local.Clear(); world.Clear(); localSigns.Clear(); worldSigns.Clear();
        for (int axis = 0; axis < 3; axis++)
        {
            ContactQuadratic n = At(normals, normalSigns, axis, Words);
            n.Rational.CopyTo(Slot(local, axis, Words)); n.Radical.CopyTo(Slot(local, axis + 3, Words));
            localSigns[axis] = n.Signs[0]; localSigns[axis + 3] = n.Signs[1];
        }
        root.CopyTo(Slot(world, 6, Words));
        var basis = new WideRationalBasis3d(rotation);
        WriteWorldDirection(basis, local[..(3 * Words)], localSigns[..3], world[..(3 * Words)], worldSigns[..3]);
        WriteWorldDirection(basis, local.Slice(3 * Words, 3 * Words), localSigns.Slice(3, 3), world.Slice(3 * Words, 3 * Words), worldSigns.Slice(3, 3));
        return WideConvexPrismRelations.GetConvexContactCandidateNormal(new ConvexContactCandidate(world, worldSigns, 0, Words));
    }
}
